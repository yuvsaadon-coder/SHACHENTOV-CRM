// ─── Article catalog → knowledge_articles (fixes "לא מסונכרן") ───────────────

async function seedArticles() {
  const src = readFileSync(resolve('src/data/knowledgeCatalog.ts'), 'utf8')
  // The catalog is a plain TS literal; pull the fields we persist without a bundler.
  const blocks = src.split(/\n  \{\n/).slice(1)
  const field = (block, name) => {
    const m = block.match(new RegExp(`${name}: '((?:[^'\\\\]|\\\\.)*)'`))
    return m ? m[1].replace(/\\'/g, "'").replace(/\\n/g, '\n') : null
  }
  const num = (block, name) => {
    const m = block.match(new RegExp(`${name}: (\\d+)`))
    return m ? Number(m[1]) : null
  }
  const list = (block, name) => {
    const m = block.match(new RegExp(`${name}: \\[([^\\]]*)\\]`))
    return m ? [...m[1].matchAll(/'([^']*)'/g)].map((x) => x[1]) : []
  }

  let count = 0
  for (const block of blocks) {
    const id = field(block, 'id')
    if (!id || !id.startsWith('art-')) continue
    const batchDoc = {
      id,
      titleHe: field(block, 'titleHe') ?? '',
      titleEn: field(block, 'titleEn'),
      lang: field(block, 'lang') ?? 'עברית',
      pages: num(block, 'pages') ?? 0,
      year: num(block, 'year'),
      source: field(block, 'source'),
      topics: list(block, 'topics'),
      summary: field(block, 'summary') ?? '',
      storageUrl: field(block, 'storageUrl'),
      updatedAt: new Date().toISOString(),
    }
    await db.collection('knowledge_articles').doc(id).set(batchDoc, { merge: true })
    await db.collection('knowledgeItems').doc(`research-${id}`).set({
      branchId: 'global',
      type: 'research_article',
      title: batchDoc.titleHe,
      content: batchDoc.summary,
      storageUrl: batchDoc.storageUrl,
      articleId: id,
      tags: batchDoc.topics,
      createdBy: 'system',
      createdAt: new Date().toISOString(),
    }, { merge: true })
    count++
  }
  return count
}

// ─── Run ────────────────────────────────────────────────────────────────────

async function main() {
  console.log('=== Seeding knowledge from source documents ===\n')

  for (const id of INVENTED_DOC_IDS) {
    await db.collection('knowledgeItems').doc(id).delete()
  }
  console.log(`✓ Removed ${INVENTED_DOC_IDS.length} unsourced items`)

  for (const item of KNOWLEDGE_ITEMS) {
    const { id, ...rest } = item
    await db.collection('knowledgeItems').doc(id).set({
      branchId: 'global',
      createdBy: 'system',
      createdAt: now(),
      ...rest,
    }, { merge: true })
  }
  console.log(`✓ ${KNOWLEDGE_ITEMS.length} coordinator knowledge items`)

  for (const [id, title, content, fileUrl, tags] of FILE_ITEMS) {
    await db.collection('knowledgeItems').doc(id).set({
      branchId: 'global',
      type: 'file',
      title,
      content,
      fileUrl,
      fileName: fileUrl.split('/').pop(),
      tags,
      createdBy: 'system',
      createdAt: now(),
    }, { merge: true })
  }
  console.log(`✓ ${FILE_ITEMS.length} downloadable documents and formats`)

  for (const item of HQ_ITEMS) {
    const { id, ...rest } = item
    await db.collection('hq_knowledge').doc(id).set({
      createdBy: 'system',
      createdAt: now(),
      ...rest,
    }, { merge: true })
  }
  console.log(`✓ ${HQ_ITEMS.length} HQ knowledge items (merged CEO handover)`)

  const articles = await seedArticles()
  console.log(`✓ ${articles} research articles synced to knowledge_articles`)

  console.log('\n=== Done ===')
  process.exit(0)
}

main().catch((err) => { console.error('Error:', err); process.exit(1) })
