export function guessEmoji(name: string): { emoji: string; cat: 'dry' | 'fresh' } {
  const n = name.replace(/[\u0591-\u05C7]/g, '').replace(/[׳'"״]/g, '').toLowerCase()
  for (const [re, emoji, cat] of RULES) if (re.test(n)) return { emoji, cat }
  return { emoji: '🛒', cat: 'dry' }
}
